//! G0/G3 original NBS oxygen sources through ideal gas/aqueous partitioning.
//! These checks establish source arithmetic and declared-model identities,
//! not a measured oxygen-transfer rate or calibrated leach performance.
#![deny(unsafe_code)]

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::OnceLock;

use fs_matdb::{NormalizedPack, PropertyKey, QueryPoint, SelectionPolicy, UncertaintyModel};
use fs_qty::{
    Amount, Dims, Pressure, QuantitySpec, Volume,
    semantic::{QuantityKind, SemanticType, ValueForm},
};
use fs_thermochem::{
    ChargeVector, ElementId, ElementalMatrix, ReactionId, SpeciesId, StoichiometricMatrix,
    stoichiometry::{
        ConservedReaction,
        thermodynamics::{FormationGibbsSource, gas_liquid::IdealGasLiquidPartition},
    },
};

const REFERENCE: &str = "source-elemental-reference-nbs1989";
const PACKS: [&str; 2] = [
    "oxygen-gas-nbs1989-thermochemistry",
    "oxygen-aqueous-nbs1989-thermochemistry",
];
// Independently evaluated to 60 decimal digits from the literal source DeltaG
// and R=8.31446261815324 J/(mol K), T=298.15 K; not generated by the candidate.
const K: f64 = 0.001_339_196_503_128_502_6;
const LOG_K: f64 = -6.615_685_469_396_972;
const RT: f64 = 8.314_462_618_153_24 * 298.15;
const P0: f64 = 100_000.0;

struct Source {
    id: SpeciesId,
    pack: NormalizedPack,
    at: QueryPoint,
}

fn workspace() -> PathBuf {
    std::env::var_os("CARGO_WORKSPACE_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .unwrap()
                .into()
        })
}

fn semantic(kind: QuantityKind) -> QuantitySpec {
    QuantitySpec::semantic(SemanticType::new(kind, ValueForm::Static))
}

fn point(gas: bool) -> QueryPoint {
    let mut at = QueryPoint::new()
        .with_quantity(
            "temperature",
            semantic(QuantityKind::AbsoluteTemperature),
            298.15,
        )
        .unwrap()
        .with_quantity("pressure", semantic(QuantityKind::Pressure), P0)
        .unwrap();
    let phase = if gas {
        "source-phase-gas"
    } else {
        "source-phase-aqueous"
    };
    let convention = if gas {
        "source-pure-species"
    } else {
        "source-aqueous-unit-activity-infinite-dilution"
    };
    for (axis, value) in [
        (REFERENCE, 1.0),
        ("source-standard-state", 1.0),
        (phase, 1.0),
        (convention, 1.0),
        ("engineering-reference-model", 1.0),
        ("source-specimen-qualified", 0.0),
    ] {
        at = at
            .with_quantity(axis, QuantitySpec::dimensional(Dims::NONE), value)
            .unwrap();
    }
    at
}

fn sources() -> &'static [Source; 2] {
    static SOURCES: OnceLock<[Source; 2]> = OnceLock::new();
    SOURCES.get_or_init(|| {
        let nonce = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let directory = std::env::temp_dir().join(format!(
            "frankensim-oxygen-partition-{}-{nonce}",
            std::process::id()
        ));
        std::fs::create_dir(&directory).unwrap();
        std::array::from_fn(|index| {
            let name = PACKS[index];
            let output = directory.join(format!("{name}.fsmatpk"));
            let run = Command::new(env!("CARGO_BIN_EXE_xtask"))
                .args(["matdb-pack", "--manifest"])
                .arg(workspace().join(format!("data/matdb/seed-v1/{name}/manifest.tsv")))
                .arg("--out")
                .arg(&output)
                .env("CARGO_WORKSPACE_DIR", workspace())
                .current_dir(workspace())
                .output()
                .unwrap();
            assert!(
                run.status.success(),
                "{name}: {}",
                String::from_utf8_lossy(&run.stderr)
            );
            let bytes = std::fs::read(output).unwrap();
            let decoded = NormalizedPack::from_bytes(&bytes).unwrap();
            let pack = NormalizedPack::from_bytes_verified(decoded.content_hash(), &bytes).unwrap();
            assert_eq!(pack.pack_id(), name);
            assert_eq!(pack.to_bytes(), bytes);
            Source {
                id: SpeciesId::new(if index == 0 { "O2(g)" } else { "O2(aq)" }).unwrap(),
                pack,
                at: point(index == 0),
            }
        })
    })
}

fn reaction() -> ConservedReaction {
    let species = sources().iter().map(|s| s.id.clone()).collect::<Vec<_>>();
    let elemental = ElementalMatrix::new(
        vec![ElementId::new("O").unwrap()],
        species.clone(),
        vec![vec![2, 2]],
    )
    .unwrap();
    let id = ReactionId::new("oxygen-gas-aqueous-partition").unwrap();
    let stoichiometric =
        StoichiometricMatrix::new(species.clone(), vec![id.clone()], vec![vec![-1], vec![1]])
            .unwrap();
    let charge = ChargeVector::new(species, vec![0, 0]).unwrap();
    ConservedReaction::new(&elemental, &stoichiometric, &charge, id).unwrap()
}

fn gibbs_sources() -> [FormationGibbsSource<'static>; 2] {
    std::array::from_fn(|i| FormationGibbsSource {
        species: &sources()[i].id,
        pack: &sources()[i].pack,
        at: &sources()[i].at,
        reference_axis: REFERENCE,
    })
}

fn model() -> IdealGasLiquidPartition {
    IdealGasLiquidPartition::from_sources(
        reaction(),
        sources()[0].id.clone(),
        sources()[1].id.clone(),
        &gibbs_sources(),
    )
    .unwrap()
}

fn relative(actual: f64, expected: f64) {
    assert!(actual.is_finite());
    assert!(
        (actual - expected).abs() <= 3e-13 * expected.abs(),
        "{actual} != {expected}"
    );
}

#[test]
fn g0_original_gas_and_aqueous_rows_supply_the_partition_constant() {
    for (source, expected) in sources().iter().zip([
        [0.031_998_8, 0.0, 0.0, 205.138],
        [0.031_998_8, -11_700.0, 16_400.0, 110.9],
    ]) {
        assert_eq!(source.pack.claims().claim_count(), 4);
        for ((key, dims), value) in [
            ("molar-mass", Dims([0, 1, 0, 0, 0, -1])),
            (
                "standard-molar-formation-enthalpy",
                Dims([2, 1, -2, 0, 0, -1]),
            ),
            (
                "standard-molar-formation-gibbs-energy",
                Dims([2, 1, -2, 0, 0, -1]),
            ),
            ("standard-molar-entropy", Dims([2, 1, -2, -1, 0, -1])),
        ]
        .into_iter()
        .zip(expected)
        {
            let answer = source
                .pack
                .claims()
                .query_typed(
                    &PropertyKey::new(key, dims),
                    &source.at,
                    SelectionPolicy::SingleClaimOnly,
                )
                .unwrap();
            relative(answer.evidence.value.value, value);
            assert_eq!(
                answer.evidence.value.uncertainty,
                UncertaintyModel::Unstated
            );
            assert!(answer.receipt.observation_backed);
            assert!(!answer.receipt.source_hashes.is_empty());
            source
                .pack
                .claims()
                .verify_receipt(&answer.receipt)
                .unwrap();
        }
    }
    let model = model();
    assert_eq!(model.gas(), &sources()[0].id);
    assert_eq!(model.aqueous(), &sources()[1].id);
    relative(model.standard().molar().value(), 16_400.0);
    relative(model.standard().log_equilibrium_constant().value(), LOG_K);
    relative(model.standard().equilibrium_constant().unwrap().value(), K);
    assert_eq!(model.standard().reference_axis(), REFERENCE);
    for term in model.standard().terms() {
        let source = sources()
            .iter()
            .find(|s| s.id == term.term.species)
            .unwrap();
        assert_eq!(term.pack_id, source.pack.pack_id());
        source
            .pack
            .claims()
            .verify_receipt(&term.answer.receipt)
            .unwrap();
    }
}

#[test]
fn g3_explicit_solvent_basis_and_finite_headspace_close_the_original_oxygen_pool() {
    let model = model();
    for pressure in [0.0, 21_000.0, 100_000.0] {
        for basis in [1.0, 1000.0] {
            let amount = model
                .equilibrium_aqueous_amount(Pressure::new(pressure), Amount::new(basis))
                .unwrap();
            relative(amount.value(), basis * K * pressure / P0);
        }
    }
    let (total, basis, volume) = (0.1, 1000.0, 0.025);
    let gas_capacity = volume / RT;
    let solution_capacity = basis * K / P0;
    let expected_pressure = total / (gas_capacity + solution_capacity);
    let result = model
        .finite_equilibrium(Amount::new(total), Amount::new(basis), Volume::new(volume))
        .unwrap();
    relative(result.partial_pressure.value(), expected_pressure);
    relative(result.gas_amount.value(), expected_pressure * gas_capacity);
    relative(
        result.aqueous_amount.value(),
        expected_pressure * solution_capacity,
    );
    relative(
        result.gas_amount.value() + result.aqueous_amount.value(),
        total,
    );
    assert!(result.component_balance_residual.value().abs() < 32.0 * f64::EPSILON * total);
    assert!(result.log_equilibrium_residual.unwrap().value().abs() < 1e-12);
    relative(
        model
            .ideal_partial_pressure(result.gas_amount, Volume::new(volume))
            .unwrap()
            .value(),
        expected_pressure,
    );
    relative(
        model
            .equilibrium_aqueous_amount(result.partial_pressure, Amount::new(basis))
            .unwrap()
            .value(),
        result.aqueous_amount.value(),
    );
    assert_eq!(result.model().standard().reference_axis(), REFERENCE);
    let scaled = model
        .finite_equilibrium(
            Amount::new(7.0 * total),
            Amount::new(7.0 * basis),
            Volume::new(7.0 * volume),
        )
        .unwrap();
    relative(
        scaled.partial_pressure.value(),
        result.partial_pressure.value(),
    );
    relative(scaled.gas_amount.value(), 7.0 * result.gas_amount.value());
    relative(
        scaled.aqueous_amount.value(),
        7.0 * result.aqueous_amount.value(),
    );
}

#[test]
fn g0_zero_trace_and_source_domain_refusals_preserve_the_declared_model() {
    let model = model();
    let empty = model
        .finite_equilibrium(Amount::new(0.0), Amount::new(1000.0), Volume::new(0.025))
        .unwrap();
    assert_eq!(empty.gas_amount.value(), 0.0);
    assert_eq!(empty.aqueous_amount.value(), 0.0);
    assert_eq!(empty.partial_pressure.value(), 0.0);
    assert_eq!(empty.component_balance_residual.value(), 0.0);
    assert!(empty.log_equilibrium_residual.is_none());
    let trace = model
        .finite_equilibrium(Amount::new(1e-200), Amount::new(1000.0), Volume::new(0.025))
        .unwrap();
    assert!(trace.gas_amount.value() > 0.0 && trace.aqueous_amount.value() > 0.0);
    relative(
        trace.gas_amount.value() + trace.aqueous_amount.value(),
        1e-200,
    );
    for bad in [-1.0, f64::INFINITY, f64::NAN] {
        assert!(
            model
                .equilibrium_aqueous_amount(Pressure::new(bad), Amount::new(1.0))
                .is_err()
        );
        assert!(
            model
                .finite_equilibrium(Amount::new(bad), Amount::new(1.0), Volume::new(1.0))
                .is_err()
        );
    }
    assert!(
        model
            .equilibrium_aqueous_amount(Pressure::new(1000.0), Amount::new(0.0))
            .is_err()
    );
    assert!(
        model
            .finite_equilibrium(Amount::new(0.1), Amount::new(1000.0), Volume::new(0.0))
            .is_err()
    );
    for at in [
        sources()[1]
            .at
            .clone()
            .with("source-phase-aqueous", 0.0)
            .unwrap(),
        sources()[1]
            .at
            .clone()
            .with_quantity(
                "temperature",
                semantic(QuantityKind::AbsoluteTemperature),
                310.0,
            )
            .unwrap(),
    ] {
        let mut selected = gibbs_sources();
        selected[1].at = &at;
        assert!(
            IdealGasLiquidPartition::from_sources(
                reaction(),
                sources()[0].id.clone(),
                sources()[1].id.clone(),
                &selected
            )
            .is_err()
        );
    }
    assert!(
        IdealGasLiquidPartition::from_sources(
            reaction(),
            sources()[1].id.clone(),
            sources()[0].id.clone(),
            &gibbs_sources()
        )
        .is_err()
    );
}
