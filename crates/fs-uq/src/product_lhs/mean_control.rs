//! Frozen physical mean controls for replicated Latin hypercubes.
//!
//! The controlled observable is Y - g^T(X-E[X]), with g fixed before sampling.
//! Complete independent hypercubes, never their dependent individual points,
//! provide the descriptive standard error. Raw model responses and compliance
//! remain untouched. No variance reduction, stopping guarantee, finite-grid
//! unbiasedness or physical-model error bound is implied.

use fs_blake3::{ContentHash, hash_domain};

use super::{LhsEstimate, LhsExecution, replicate_estimate, scaled_mean_interruptible};
use crate::UqStatus;
use crate::product_checkpoint::execution_identity;
use crate::product_control_variate::{
    LinearControlVariate, UqControlError, adjusted_samples, poll,
};

/// Predictor fixed before observations and bound to the complete LHS plan.
/// The caller owns the coefficient/model binding and must not choose gradients
/// using these observations, including by constructing a fresh execution later.
#[derive(Debug, Clone)]
pub struct LhsLinearControlVariate {
    sampling_identity: ContentHash,
    control: LinearControlVariate,
}

fn identity(execution: &LhsExecution) -> ContentHash {
    let domain = hash_domain("org.frankensim.uq.lhs-linear-control.v1", &[]);
    execution_identity(
        &execution.storage.plan,
        execution.checkpoint_identity(domain),
    )
}

impl LhsLinearControlVariate {
    /// Distribution means in the declared physical coordinate order.
    #[must_use]
    pub fn parameter_means(&self) -> &[f64] {
        self.control.parameter_means()
    }

    /// Frozen coefficients in QoI units per declared parameter unit.
    #[must_use]
    pub fn gradient(&self) -> &[f64] {
        self.control.gradient()
    }
}

/// Raw and controlled mean estimates from the same complete hypercubes.
/// Adjusted samples are estimators, not a physical QoI distribution; no adjusted
/// quantile, extremum, compliance probability or individual-point error is exposed.
#[derive(Debug, Clone, PartialEq)]
pub struct LhsLinearControlEstimate {
    /// Accepted physical responses, including an unfinished replicate.
    pub samples_accepted: usize,
    /// Responses used in either estimate, a whole number of hypercubes.
    pub samples_in_estimate: usize,
    /// Complete independent hypercubes, the statistical sample size.
    pub completed_replicates: usize,
    /// Original, immutable stratum count per hypercube.
    pub samples_per_replicate: usize,
    /// Raw means in replicate order.
    pub raw_replicate_means: Vec<f64>,
    /// Controlled means in that same order.
    pub controlled_replicate_means: Vec<f64>,
    /// Absent before the first complete hypercube. Standard error requires two.
    pub raw: Option<LhsEstimate>,
    /// Mean and descriptive between-replicate error of the controlled observable.
    pub controlled: Option<LhsEstimate>,
    /// Controlled/raw between-replicate variance, not clipped to imply benefit.
    /// Absent for unavailable/zero raw dispersion or an unrepresentable ratio.
    pub variance_ratio: Option<f64>,
}

impl LhsExecution {
    /// Freeze physical mean coefficients before any accepted or failed model call.
    /// Reuses the existing marginal expectation and coefficient admission owner;
    /// no Monte Carlo samples are generated by this operation.
    pub fn freeze_linear_control_variate(
        &self,
        gradient: &[f64],
    ) -> Result<LhsLinearControlVariate, UqControlError> {
        Ok(LhsLinearControlVariate {
            sampling_identity: identity(self),
            control: self.storage.freeze_linear_control_variate(gradient)?,
        })
    }

    /// Regenerate only sampler coordinates, without rerunning physical callbacks.
    pub fn assess_linear_control_variate(
        &self,
        control: &LhsLinearControlVariate,
    ) -> Result<LhsLinearControlEstimate, UqControlError> {
        self.assess_linear_control_variate_interruptible(control, || false)
    }

    /// Assess complete replicates with O(n*d) sampler work and bounded storage
    /// for one permutation design and one adjusted replicate. Cancellation polls
    /// before each sample, during permutation construction and every 512 reduction
    /// entries. Raw observations, counts, reports and checkpoint bytes never change.
    /// Changing any plan field, failed execution, nonfinite control arithmetic or
    /// interruption refuses the entire assessment; no selected prefix is returned.
    pub fn assess_linear_control_variate_interruptible(
        &self,
        control: &LhsLinearControlVariate,
        mut cancelled: impl FnMut() -> bool,
    ) -> Result<LhsLinearControlEstimate, UqControlError> {
        if identity(self) != control.sampling_identity {
            return Err(UqControlError::PlanMismatch);
        }
        if self.storage.status == UqStatus::Refused || self.storage.failure.is_some() {
            return Err(UqControlError::RefusedExecution);
        }
        poll(&mut cancelled)?;
        // A fresh executor owns no observations. Do not clone self: a paid
        // sample prefix can contain one million values and must stay borrowed.
        let mut replay = Self::new(&self.plan).map_err(|_| UqControlError::PlanMismatch)?;
        let size = self.plan.samples_per_replicate;
        let complete = self.storage.values.len() / size;
        let mut raw_means = Vec::with_capacity(complete);
        let mut controlled_means = Vec::with_capacity(complete);
        for (replicate, values) in self.storage.values.chunks_exact(size).enumerate() {
            if !replay
                .build_design(replicate, &mut cancelled)
                .map_err(|_| UqControlError::NumericalRange)?
            {
                return Err(UqControlError::Cancelled);
            }
            let adjusted = adjusted_samples(
                &control.control,
                values,
                |index| {
                    replay
                        .parameters(replicate * size + index)
                        .map_err(|_| UqControlError::NumericalRange)
                },
                &mut cancelled,
            )?;
            raw_means.push(scaled_mean_interruptible(values, &mut cancelled)?);
            controlled_means.push(scaled_mean_interruptible(&adjusted, &mut cancelled)?);
        }
        poll(&mut cancelled)?;
        // At most 256 means; use the same numerical owner as the raw LHS report.
        let raw = replicate_estimate(&raw_means);
        let controlled = replicate_estimate(&controlled_means);
        let variance_ratio = raw
            .as_ref()
            .and_then(|v| v.standard_error)
            .zip(controlled.as_ref().and_then(|v| v.standard_error))
            .and_then(|(raw, adjusted)| {
                if raw == 0.0 {
                    return None;
                }
                let ratio = (adjusted / raw).powi(2);
                ratio.is_finite().then_some(ratio)
            });
        poll(&mut cancelled)?;
        Ok(LhsLinearControlEstimate {
            samples_accepted: self.storage.values.len(),
            samples_in_estimate: complete * size,
            completed_replicates: complete,
            samples_per_replicate: size,
            raw_replicate_means: raw_means,
            controlled_replicate_means: controlled_means,
            raw,
            controlled,
            variance_ratio,
        })
    }
}

