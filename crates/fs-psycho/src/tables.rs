//! (standards.iso.org/iso/532/-1/ed-1/en, Annex A.4,
//! ISO_532-1_LIB/src/ISO_532-1.c). Table names and semantics follow
//! the reference source; see that file for the standard's own
//! comments. TWO executed extraction lessons, both certified
//! end-to-end by reference-binary values:
//! - the C source writes some entries as leading-dot floats like
//!   `-.25f`, which a naive number pattern mangles into `25`;
//! - the C tables are FLOAT LITERALS assigned into doubles, so the
//!   binary computes with the float32 ROUNDING of each decimal
//!   (`-0.6f` is -0.60000002384185791); parsing them as exact
//!   doubles left a ~4e-8 relative loudness error that a 1e-3 gate
//!   never saw — the values below are round-tripped through f32
//!   exactly as the compiler does it.

