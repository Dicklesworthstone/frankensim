/// One accepted interval: the circuit's differential state (inductor flux
/// linkages \[Wb\], then capacitor charges \[C\]), the two cells' temperatures
/// \[K\], the Joule heat \[J\], the heat \[J\] that entered the cells
/// from outside the circuit, and the entropy \[J/K\] generated by the
/// circuit's losses at their cells and by conduction among the cells.
#[derive(Debug, Clone)]
struct Row {
    state: Vec<f64>,
    kelvin: [f64; 2],
    joule_j: f64,
    outside_j: f64,
    entropy_j_k: [f64; 2],
}

/// A device of the module's tests: its netlist, whose resistances are
/// placeholders the cards replace, its mutual inductances, its start, and
/// the independent heat sources \[W\] on the cells, in [`CELLS`] order.
struct Device {
    netlist: CircuitGraph,
    mutual: Vec<MutualInductance>,
    fluxes_wb: Vec<f64>,
    charges_c: Vec<f64>,
    sources_w: [f64; 2],
}

/// The module's run: `steps` intervals of `dt_s` with `entropy::step_candidate`
/// (the module's step with its entropy account), the device built as the
/// module's tests build it. Its sources are the coefficients' `sources_w` of
/// every trial.
fn module_run(
    device: &Device,
    cards: &[MaterialCard; 2],
    curves: &[ResolvedHeatCapacityCurve; 2],
    conductance_w_k: f64,
    dt_s: f64,
    steps: usize,
) -> Vec<Row> {
    let mut thermal = initial(curves, conductance_w_k, None);
    let mut electrical = MaterialCircuit::new_with_mutual_inductance(
        device.netlist.clone(),
        coefficients(&thermal, cards, curves).unwrap().resistors,
        device.mutual.clone(),
        device.fluxes_wb.clone(),
        device.charges_c.clone(),
        &[],
    )
    .unwrap();
    let mut rows = Vec::new();
    for k in 1..=steps {
        let (next, audit) = entropy::step_candidate(
            &thermal,
            k as f64 * dt_s,
            input(&electrical),
            config(),
            &[0.0; 2],
            |s| {
                let mut found = coefficients(s, cards, curves)?;
                for (&cell, &watts) in CELLS.iter().zip(&device.sources_w) {
                    if watts != 0.0 {
                        found.sources_w.insert(cell, watts);
                    }
                }
                Ok::<_, JouleHeatingError>(found)
            },
            || false,
        )
        .unwrap();
        let circuit = next.circuit();
        rows.push(Row {
            state: circuit
                .fluxes_wb()
                .iter()
                .chain(circuit.charges_c())
                .copied()
                .collect(),
            kelvin: CELLS.map(|id| next.thermal().temperature_k(id).unwrap()),
            joule_j: next.report().deposited_joule_j,
            outside_j: next.report().non_electrical_heat_j,
            entropy_j_k: [
                audit.electrical_loss_generation_j_k,
                audit.conduction_generation_j_k,
            ],
        });
        let (t, c, _) = next.into_parts();
        thermal = t;
        electrical = c;
    }
    rows
}

/// The same device as a graph: its netlist with each resistor following its
/// card, the cells of [`timeline`], one heat route per resistor into its
/// destination cell.
fn graph(
    device: &Device,
    cards: &'static [MaterialCard; 2],
    curves: &'static [ResolvedHeatCapacityCurve; 2],
    conductance_w_k: f64,
    dt_s: f64,
) -> (System, NodeId, NodeId) {
    let (timeline, cells_start) = timeline(curves, conductance_w_k, device.sources_w, dt_s);
    let start = sourced(curves, conductance_w_k, None, device.sources_w);
    let mut circuit =
        KirchhoffCircuit::new(device.netlist.clone(), device.mutual.clone(), 1e-8).unwrap();
    for (tag, (destination, (card, curve))) in
        (0_u64..).zip(DESTINATIONS.iter().zip(cards.iter().zip(curves.iter())))
    {
        circuit = circuit
            .following(
                destination.branch,
                Arc::new(CardResistance {
                    card,
                    curve,
                    volume_m3: start.cells()[&destination.cell].geometry.volume_m3,
                    tag,
                }),
            )
            .unwrap();
    }
    let state = circuit.state(&device.fluxes_wb, &device.charges_c).unwrap();

    let mut builder = SystemBuilder::new();
    let electrical = builder.add("circuit", circuit, state).unwrap();
    let cells = builder.add("cells", timeline, cells_start).unwrap();
    for destination in DESTINATIONS {
        builder
            .heat_route(
                builder
                    .port(electrical, &format!("heat{}", destination.branch))
                    .unwrap(),
                &[(
                    builder
                        .port(cells, &format!("cell{}", destination.cell.0))
                        .unwrap(),
                    1.0,
                )],
                None,
                RouteTemperature::SinkEquivalent,
            )
            .unwrap();
    }
    builder
        .heat_route(
            builder.port(cells, "environment").unwrap(),
            &[],
            Some(heat_sink("environment", 300.0).unwrap()),
            RouteTemperature::Fixed(300.0),
        )
        .unwrap();
    let mut system = builder.seal().unwrap();
    for destination in DESTINATIONS {
        let port = system
            .port(electrical, &format!("heat{}", destination.branch))
            .unwrap();
        assert!(system.guess(port, &[300.0]));
    }
    (system, electrical, cells)
}

fn graph_run(
    system: &mut System,
    electrical: NodeId,
    cells: NodeId,
    dt_s: f64,
    steps: usize,
) -> Vec<Row> {
    let mut rows = Vec::new();
    let (mut joule_before, mut outside_before) = (0.0, 0.0);
    let mut entropy_before = [0.0; 2];
    with_cx(|cx| {
        for _ in 0..steps {
            let report = system.step(dt_s, cx).unwrap();
            assert_eq!(
                report.dt_s.to_bits(),
                dt_s.to_bits(),
                "the kernel took the whole interval"
            );
            let ledger = system.ledger();
            let joule = ledger.nodes[electrical.index()].dissipated_j.value();
            // What the cells' authored sources put in came from the
            // environment sink: minus the heat the sink received.
            let outside = -ledger.sinks[0].heat_j.value();
            let entropy = [electrical, cells]
                .map(|node| ledger.nodes[node.index()].entropy_generated_j_per_k.value());
            let timeline = system.state::<TimelineState<'static>>(cells).unwrap();
            rows.push(Row {
                state: system.state::<Vec<f64>>(electrical).unwrap().clone(),
                kelvin: CELLS.map(|id| timeline.simulation().temperature_k(id).unwrap()),
                joule_j: joule - joule_before,
                outside_j: outside - outside_before,
                entropy_j_k: [0, 1].map(|i| entropy[i] - entropy_before[i]),
            });
            (joule_before, outside_before, entropy_before) = (joule, outside, entropy);
        }
    });
    rows
}

/// Bounds of one comparison: temperature \[K\], state coordinate \[Wb or C\],
/// Joule and outside heat per interval \[J\], and each entropy term per
/// interval \[J/K\].
struct Bounds {
    kelvin: f64,
    state: f64,
    joule_j: f64,
    entropy_j_k: f64,
}

/// Runs the device both ways, the cells joined by `conductance` \[W/K\],
/// and holds every interval to `bounds`. Returns the module's rows. The
/// kernel's ledger closes, the environment sink gave the cells what their
/// sources took in, the energy that left the circuit is in the cells beside
/// it, and the circuit and the cells generate the ledger's entropy: the heat
/// routes carry only the interface iteration's residue, the heat times the
/// difference of the reciprocal temperatures the port and the cell last saw.
fn compare(
    device: &Device,
    cards: &'static [MaterialCard; 2],
    curves: &'static [ResolvedHeatCapacityCurve; 2],
    (conductance, dt, steps): (f64, f64, usize),
    bounds: &Bounds,
) -> Vec<Row> {
    let module = module_run(device, cards, curves, conductance, dt, steps);
    let (mut system, electrical, cells) = graph(device, cards, curves, conductance, dt);
    let kernel = graph_run(&mut system, electrical, cells, dt, steps);
    assert_eq!((kernel.len(), module.len()), (steps, steps));
    for (k, (ours, theirs)) in kernel.iter().zip(&module).enumerate() {
        for cell in 0..2 {
            let (x, y) = (ours.kelvin[cell], theirs.kelvin[cell]);
            assert!(
                (x - y).abs() <= bounds.kelvin,
                "interval {k}, cell {cell}: {x} vs {y}"
            );
        }
        assert_eq!(ours.state.len(), theirs.state.len());
        for (i, (x, y)) in ours.state.iter().zip(&theirs.state).enumerate() {
            assert!(
                (x - y).abs() <= bounds.state,
                "interval {k}, coordinate {i}: {x} vs {y}"
            );
        }
        assert!(
            (ours.joule_j - theirs.joule_j).abs() <= bounds.joule_j,
            "interval {k}: {} vs {}",
            ours.joule_j,
            theirs.joule_j
        );
        assert!(
            (ours.outside_j - theirs.outside_j).abs() <= bounds.joule_j,
            "interval {k}, outside heat: {} vs {}",
            ours.outside_j,
            theirs.outside_j
        );
        for (term, (x, y)) in ours.entropy_j_k.iter().zip(&theirs.entropy_j_k).enumerate() {
            assert!(
                *y > 0.0 && (x - y).abs() <= bounds.entropy_j_k,
                "interval {k}, entropy term {term}: {x} vs {y}"
            );
        }
    }
    let ledger = system.ledger();
    assert!(
        ledger.energy_residual_j().abs() <= 1e-8,
        "{}",
        ledger.energy_residual_j()
    );
    let sources_j = device.sources_w.iter().sum::<f64>() * dt * steps as f64;
    assert_eq!(ledger.sinks.len(), 1);
    let outside = -ledger.sinks[0].heat_j.value();
    assert!(
        (outside - sources_j).abs() <= 1e-8,
        "{outside} vs {sources_j}"
    );
    let released = -ledger.nodes[electrical.index()].stored_change_j.value();
    let stored = ledger.nodes[cells.index()].stored_change_j.value();
    assert!(
        released > 1.0 && (stored - released - outside).abs() <= 1e-8,
        "{stored} vs {released} + {outside}"
    );
    let nodes = [electrical, cells]
        .map(|node| ledger.nodes[node.index()].entropy_generated_j_per_k.value());
    let total = ledger.entropy_generated_j_per_k();
    // The largest residue measured is 5.4e-16 J/K, 4.3e-15 of the total.
    assert!(
        (total - nodes[0] - nodes[1]).abs() <= 2e-13 * total,
        "{total} vs {nodes:?}"
    );
    module
}

fn cards(
    alphas: [f64; 2],
) -> (
    &'static [MaterialCard; 2],
    &'static [ResolvedHeatCapacityCurve; 2],
) {
    let (a, ca) = material(1.0, 1.0, alphas[0]);
    let (b, cb) = material(3.0, 2.0, alphas[1]);
    (Box::leak(Box::new([a, b])), Box::leak(Box::new([ca, cb])))
}

#[test]
fn the_declared_graph_reproduces_the_endpoint_resistance_feedback() {
    // The module's own feedback fixture: a 1 F capacitor at 10 C through the
    // two card resistors, resistor 0 rising 0.5 % per kelvin, the cells
    // sharing a 1 W/K link, eight quarter-second intervals.
    let (cards, curves) = cards([0.005, 0.0]);
    let device = Device {
        netlist: CircuitGraph {
            node_count: 3,
            branches: vec![
                (1, 0, Branch::Capacitor { farads: 1.0 }),
                (1, 2, Branch::Resistor { ohms: 999.0 }),
                (2, 0, Branch::Resistor { ohms: 999.0 }),
            ],
            transformers: vec![],
        },
        mutual: vec![],
        fluxes_wb: vec![],
        charges_c: vec![10.0],
        sources_w: [0.0; 2],
    };
    // Temperatures and charge agree bit for bit over the first four
    // intervals and the Joule heat within 9e-16 J; after that all agree
    // within 2e-9 K, 1.4e-12 C and 4e-12 J (export of 1e611fdf33): the
    // module's Newton and the kernel's interface iteration stop at
    // different points inside their tolerances. The module's entropy terms
    // agree with the circuit's and the cells' within 1.7e-14 J/K (of 7.8e-3
    // and 2.2e-6). The bounds sit about fifty times above that, far below
    // the module's own 1e-6 J stop.
    let bounds = Bounds {
        kelvin: 1e-7,
        state: 1e-10,
        joule_j: 2e-10,
        entropy_j_k: 1e-12,
    };
    let module = compare(&device, cards, curves, (1.0, 0.25, 8), &bounds);
    // The feedback is real: cell 30 warms by kelvins, so resistor 0 moves by
    // several percent of itself over the run.
    assert!(module[7].kelvin[0] > 302.0, "{:?}", module[7]);
}

#[test]
fn the_declared_graph_reproduces_mutual_coils_with_both_resistors_following_their_cards() {
    // The module's mutual-coil fixture: 2 H and 3 H coupled by 1 H, each
    // shunted by a card resistor (0.5 % and 0.2 % per kelvin), linkages
    // 3.5 and 0.5 Wb, six quarter-second intervals.
    let (cards, curves) = cards([0.005, 0.002]);
    let device = Device {
        netlist: CircuitGraph {
            node_count: 3,
            branches: vec![
                (1, 0, Branch::Inductor { henries: 2.0 }),
                (1, 0, Branch::Resistor { ohms: 999.0 }),
                (2, 0, Branch::Resistor { ohms: 999.0 }),
                (2, 0, Branch::Inductor { henries: 3.0 }),
            ],
            transformers: vec![],
        },
        mutual: vec![MutualInductance {
            branches: (0, 3),
            henries: 1.0,
        }],
        fluxes_wb: vec![3.5, 0.5],
        charges_c: vec![],
        sources_w: [0.0; 2],
    };
    // On the export of 1e611fdf33 the two agree within 2e-9 K, 1.1e-11 Wb,
    // 7.1e-12 J and 6.6e-15 J/K at every interval; the bounds sit about
    // fifty times above that.
    let bounds = Bounds {
        kelvin: 1e-7,
        state: 5e-10,
        joule_j: 4e-10,
        entropy_j_k: 3e-13,
    };
    let module = compare(&device, cards, curves, (1.0, 0.25, 6), &bounds);
    assert!(module[5].kelvin[0] > 300.5, "{:?}", module[5]);
}

#[test]
fn the_declared_graph_keeps_independent_cell_sources_apart_from_the_joule_heat() {
    // The module's independent-sources fixture: the capacitor device with
    // constant cards, a 2 W/K link, 2 W into cell 30 and 1 W out of cell 10,
    // which the module resolves as coefficients and the graph as the cells'
    // authored boundary sources. The module steps one second; this runs
    // three.
    let (cards, curves) = cards([0.0, 0.0]);
    let device = Device {
        netlist: CircuitGraph {
            node_count: 3,
            branches: vec![
                (1, 0, Branch::Capacitor { farads: 1.0 }),
                (1, 2, Branch::Resistor { ohms: 999.0 }),
                (2, 0, Branch::Resistor { ohms: 999.0 }),
            ],
            transformers: vec![],
        },
        mutual: vec![],
        fluxes_wb: vec![],
        charges_c: vec![10.0],
        sources_w: [2.0, -1.0],
    };
    // On the export of 1e611fdf33 the charge agrees bit for bit at every
    // interval, the temperatures within 3e-12 K, the Joule heat within
    // 4e-15 J, the entropy terms within 3.5e-16 J/K, and the outside heat
    // exactly: 1 J an interval on both sides. The temperature and entropy
    // bounds sit about fifty times above that; the others are those of the
    // capacitor fixture above.
    let bounds = Bounds {
        kelvin: 1.5e-10,
        state: 1e-10,
        joule_j: 2e-10,
        entropy_j_k: 2e-14,
    };
    let module = compare(&device, cards, curves, (2.0, 1.0, 3), &bounds);
    // The module's own check: one joule an interval that is not electrical.
    assert!(
        module.iter().all(|row| (row.outside_j - 1.0).abs() < 3e-6),
        "{module:?}"
    );
}
