//! Independent pressure moment, rigid trace and full-impedance regressions.

use super::{CountedFluid, boundary_edges, material, near, zero};
use fs_couple::stokes_motion::planar::{
    PlanarStokesConfig, PlanarStokesControls, PlanarStokesError, PlanarStokesMotion,
};
use fs_flux::bdm::edge_gauss_pub;
use fs_flux::{FluxSystem, MaterialFluxNumerics, TriMesh};
use fs_mbd::{MassProperties, Pose, RigidBodyState, UnitQuaternion, Vec3};
use fs_solid::Mesh2;
use std::cell::Cell;

fn config() -> PlanarStokesConfig {
    PlanarStokesConfig {
        depth_m: 0.3,
        max_translation_m: 0.02,
        max_rotation_rad: 0.03,
        translation_stiffness_n_m: [0.0; 2],
        rotation_stiffness_n_m_rad: 0.0,
        translation_damping_n_s_m: [0.0; 2],
        rotation_damping_n_m_s_rad: 0.0,
        velocity_tolerance_m_s: 1e-8,
        angular_velocity_tolerance_rad_s: 1e-8,
    }
}

fn properties() -> MassProperties {
    MassProperties::new(0.7, Vec3::ZERO, Vec3::new(0.15, 0.15, 0.2)).unwrap()
}

fn body(rates: [f64; 3]) -> RigidBodyState {
    RigidBodyState::new(
        Pose::new(Vec3::new(0.2, 0.1, 0.4), UnitQuaternion::IDENTITY).unwrap(),
        Vec3::new(0.7 * rates[0], 0.7 * rates[1], 0.0),
        Vec3::new(0.0, 0.0, 0.2 * rates[2]),
    )
    .unwrap()
}

// Independently integrate BOTH original edge moments; do not reproduce the
// closed-form rotational linear moment used by the production admission check.
fn rigid_history(mesh: &TriMesh, rates: [f64; 3]) -> Vec<f64> {
    let mut history = vec![0.0; 2 * mesh.edges.len()];
    for (edge, geometry) in mesh.edges.iter().enumerate() {
        let a = mesh.verts[geometry.verts.0];
        let b = mesh.verts[geometry.verts.1];
        for (point, weight) in edge_gauss_pub(a, b) {
            let u = [
                rates[0] - rates[2] * (point[1] - 0.1),
                rates[1] + rates[2] * (point[0] - 0.2),
            ];
            let vn = u[0] * geometry.normal[0] + u[1] * geometry.normal[1];
            let s = ((point[0] - a[0]) * (b[0] - a[0]) + (point[1] - a[1]) * (b[1] - a[1]))
                / geometry.len.powi(2)
                - 0.5;
            history[2 * edge] += weight * vn / geometry.len;
            history[2 * edge + 1] += weight * vn * s / geometry.len;
        }
    }
    history
}

#[test]
fn linear_pressure_drives_two_translations_and_rotation_with_native_pose() {
    let mesh = TriMesh::from_mesh2(&Mesh2::triangles(2.0, 1.0, 3, 2));
    let system = FluxSystem::new(&mesh);
    let edges = boundary_edges(&mesh);
    let fluid = material(2.0, 0.8);
    let dt = 0.001;
    let gradient = [0.4, -0.3];
    for depth in [0.3, 0.7] {
        let cfg = PlanarStokesConfig {
            depth_m: depth,
            ..config()
        };
        let volume = 2.0 * depth;
        let force = gradient.map(|g| volume * g);
        // Divergence theorem: integral_boundary p*(r cross n) =
        // volume * ((centroid - reference_COM) cross grad(p)).
        let torque = volume * (0.8 * gradient[1] - 0.4 * gradient[0]);
        let acceleration = [force[0] / 0.7, force[1] / 0.7, torque / 0.2];
        let expected = acceleration.map(|a| dt * a);
        // Angular acceleration has nonzero curl: it cannot be generated by
        // pressure alone. Supply the matching affine inertial body force.
        let density_force = |p: [f64; 2]| {
            [
                2.0 * (acceleration[0] - acceleration[2] * (p[1] - 0.1)) + gradient[0],
                2.0 * (acceleration[1] + acceleration[2] * (p[0] - 0.2)) + gradient[1],
            ]
        };
        let mut motion = PlanarStokesMotion::new(
            &system,
            &fluid,
            MaterialFluxNumerics::default(),
            properties(),
            body([0.0; 3]),
            vec![0.0; system.n_u],
            &edges,
            cfg,
        )
        .unwrap();
        let step = motion
            .step(
                dt,
                &density_force,
                &[],
                &[Some(10.0)],
                [0.0; 2],
                0.0,
                PlanarStokesControls::default(),
                || false,
            )
            .unwrap();
        for axis in 0..2 {
            near(step.velocity_m_s[axis], expected[axis], 2e-9);
            near(step.fluid_force_n[axis], force[axis], 2e-7);
            near(
                motion.state().translation_m()[axis],
                dt * expected[axis],
                2e-11,
            );
        }
        near(step.angular_velocity_rad_s, expected[2], 2e-9);
        near(step.fluid_torque_n_m, torque, 2e-7);
        near(motion.state().rotation_rad(), dt * expected[2], 2e-11);
        let exact_velocity = |p: [f64; 2]| {
            [
                expected[0] - expected[2] * (p[1] - 0.1),
                expected[1] + expected[2] * (p[0] - 0.2),
            ]
        };
        let (error, divergence) = system.velocity_error(&step.flow.discrete().x, &exact_velocity);
        assert!(error < 3e-9 && divergence < 3e-9);
        let moments = rigid_history(&mesh, expected);
        assert!(edges.iter().any(|&e| moments[2 * e + 1].abs() > 1e-6));
        for &edge in &edges {
            near(
                step.flow.velocity_dofs()[2 * edge + 1],
                moments[2 * edge + 1],
                2e-9,
            );
        }
        let p = step.body_after.pose().position_world();
        near(p.x, 0.2 + dt * expected[0], 2e-11);
        near(p.y, 0.1 + dt * expected[1], 2e-11);
        assert_eq!(p.z, 0.4);
        let q = step.body_after.pose().orientation().components();
        near(q[0], (0.5 * dt * expected[2]).cos(), 2e-11);
        near(q[3], (0.5 * dt * expected[2]).sin(), 2e-11);
        assert_eq!(q[1], 0.0);
        assert_eq!(q[2], 0.0);
        // An independent zero-initial-momentum body identity: BE work equals
        // twice endpoint kinetic energy, without requiring a fluid heat claim.
        let work = dt * (force[0] * expected[0] + force[1] * expected[1] + torque * expected[2]);
        let kinetic = 0.5 * 0.7 * (expected[0].powi(2) + expected[1].powi(2))
            + 0.5 * 0.2 * expected[2].powi(2);
        near(step.interface_work_j, work, 3e-10);
        near(step.body_kinetic_change_j, kinetic, 3e-10);
        near(step.mechanical_time_discretization_loss_j, kinetic, 3e-10);
        near(step.bulk_viscous_dissipation_j, 0.0, 1e-16);
        near(step.mechanical_work_residual_j, 0.0, 3e-10);
        assert_eq!(step.boundary_load.origin_m, [0.2, 0.1]);
        assert_eq!(
            step.boundary_load.pressure_offsets_pa,
            vec![(0, Some(10.0))]
        );
    }
}

#[test]
fn off_center_fluid_impedance_keeps_reciprocal_translation_rotation_terms() {
    let mesh = TriMesh::from_mesh2(&Mesh2::triangles(2.0, 1.0, 3, 2));
    let system = FluxSystem::new(&mesh);
    let edges = boundary_edges(&mesh);
    let dt = 0.002;
    let cfg = PlanarStokesConfig {
        translation_stiffness_n_m: [7.0, 11.0],
        rotation_stiffness_n_m_rad: 1.7,
        translation_damping_n_s_m: [0.4, 0.6],
        rotation_damping_n_m_s_rad: 0.2,
        ..config()
    };
    let mut angular_rates = Vec::new();
    for viscosity in [0.08, 8.0] {
        let fluid = material(2.0, viscosity);
        let mut motion = PlanarStokesMotion::new(
            &system,
            &fluid,
            MaterialFluxNumerics::default(),
            properties(),
            body([0.0; 3]),
            vec![0.0; system.n_u],
            &edges,
            cfg,
        )
        .unwrap();
        let step = motion
            .step(
                dt,
                &zero,
                &[],
                &[Some(23.0)],
                [0.0; 2],
                0.6,
                PlanarStokesControls::default(),
                || false,
            )
            .unwrap();
        let z = step.fluid_impedance;
        let mass_rate = 2.0 * 2.0 * cfg.depth_m / dt;
        // Translation is exactly uniform. The off-center reference creates
        // known translation/rotation cross terms through linear momentum;
        // rotation's unknown diagonal is NOT a guessed polar added inertia.
        near(z[0][0], -mass_rate, 3e-6);
        near(z[1][1], -mass_rate, 3e-6);
        near(z[0][1], 0.0, 3e-6);
        near(z[1][0], 0.0, 3e-6);
        near(z[2][0], 0.4 * mass_rate, 3e-6);
        near(z[2][1], -0.8 * mass_rate, 3e-6);
        near(z[0][2], z[2][0], 3e-6);
        near(z[1][2], z[2][1], 3e-6);
        assert!(step.angular_velocity_rad_s > 0.0);
        assert!(step.velocity_m_s[0] > 0.0 && step.velocity_m_s[1] < 0.0);
        assert!(step.interface_work_j < 0.0 && step.fluid_kinetic_change_j > 0.0);
        assert!(step.damping_loss_j > 0.0 && step.spring_energy_change_j > 0.0);
        for residual in step.force_residual_n {
            near(residual, 0.0, 3e-8);
        }
        near(step.torque_residual_n_m, 0.0, 3e-8);
        near(step.mechanical_work_residual_j, 0.0, 3e-10);
        angular_rates.push(step.angular_velocity_rad_s);
    }
    assert!(
        angular_rates[1] < angular_rates[0],
        "larger resolved viscosity must impede the same applied torque"
    );
}

#[test]
fn late_cancellation_and_rotation_limit_preserve_the_complete_continuation() {
    let mesh = TriMesh::from_mesh2(&Mesh2::triangles(2.0, 1.0, 2, 2));
    let system = FluxSystem::new(&mesh);
    let edges = boundary_edges(&mesh);
    let fluid = CountedFluid {
        state: material(2.0, 0.8),
        queries: Cell::new(0),
    };
    let cfg = config();
    let make = |cfg| {
        PlanarStokesMotion::new(
            &system,
            &fluid,
            MaterialFluxNumerics::default(),
            properties(),
            body([0.0; 3]),
            vec![0.0; system.n_u],
            &edges,
            cfg,
        )
        .unwrap()
    };
    let mut motion = make(cfg);
    let mut reference = make(cfg);
    let queries = fluid.queries.get();
    let controls = PlanarStokesControls::default();
    for owner in [&mut motion, &mut reference] {
        owner
            .step(
                0.002,
                &zero,
                &[],
                &[Some(1.0)],
                [0.3, -0.2],
                0.6,
                controls,
                || false,
            )
            .unwrap();
    }
    let before = motion.state().clone();
    let mut polls = 0;
    let failure = motion.step(
        0.002,
        &zero,
        &[],
        &[Some(1.0)],
        [0.3, -0.2],
        0.6,
        controls,
        || {
            polls += 1;
            polls == 7 // Final publication, after the endpoint flow and work gates.
        },
    );
    assert!(matches!(failure, Err(PlanarStokesError::Cancelled)));
    assert_eq!(polls, 7);
    assert_eq!(motion.state(), &before);
    for owner in [&mut motion, &mut reference] {
        owner
            .step(
                0.002,
                &zero,
                &[],
                &[Some(1.0)],
                [0.3, -0.2],
                0.6,
                controls,
                || false,
            )
            .unwrap();
    }
    assert_eq!(motion.state(), reference.state());
    assert_eq!(
        fluid.queries.get(),
        queries,
        "trial solves must retain the original transport snapshot"
    );
    assert!(std::ptr::eq(motion.material(), &fluid));
    let mut bounded = make(PlanarStokesConfig {
        max_rotation_rad: 1e-15,
        ..cfg
    });
    let before = bounded.state().clone();
    assert!(matches!(
        bounded.step(
            0.002,
            &zero,
            &[],
            &[Some(1.0)],
            [0.0; 2],
            0.6,
            controls,
            || false
        ),
        Err(PlanarStokesError::RotationLimit { .. })
    ));
    assert_eq!(bounded.state(), &before);
    let before = motion.state().clone();
    assert!(
        motion
            .step(0.002, &zero, &[], &[None], [0.0; 2], 0.0, controls, || {
                false
            })
            .is_err()
    );
    assert_eq!(
        motion.state(),
        &before,
        "mean-zero pressure must retain an explicit datum"
    );
}

#[test]
fn planar_admission_checks_rotational_moments_and_native_inertia_axes() {
    let mesh = TriMesh::from_mesh2(&Mesh2::triangles(2.0, 1.0, 2, 2));
    let system = FluxSystem::new(&mesh);
    let edges = boundary_edges(&mesh);
    let fluid = material(2.0, 0.8);
    let rates = [0.01, -0.02, 0.03];
    let history = rigid_history(&mesh, rates);
    let make = |properties, body, history| {
        PlanarStokesMotion::new(
            &system,
            &fluid,
            MaterialFluxNumerics::default(),
            properties,
            body,
            history,
            &edges,
            config(),
        )
    };
    assert!(make(properties(), body(rates), history.clone()).is_ok());
    let mut missing_linear = history.clone();
    for &edge in &edges {
        missing_linear[2 * edge + 1] = 0.0;
    }
    assert!(matches!(
        make(properties(), body(rates), missing_linear),
        Err(PlanarStokesError::InterfaceVelocity { .. })
    ));
    let tilted = RigidBodyState::new(
        Pose::new(
            Vec3::new(0.2, 0.1, 0.4),
            UnitQuaternion::from_axis_angle(Vec3::new(1.0, 0.0, 0.0), 0.1).unwrap(),
        )
        .unwrap(),
        Vec3::ZERO,
        Vec3::ZERO,
    )
    .unwrap();
    assert!(matches!(
        make(properties(), tilted, vec![0.0; system.n_u]),
        Err(PlanarStokesError::Invalid(_))
    ));
    let nonprincipal = MassProperties::from_principal_frame(
        0.7,
        Vec3::ZERO,
        Vec3::new(0.15, 0.15, 0.2),
        UnitQuaternion::from_axis_angle(Vec3::new(1.0, 0.0, 0.0), 0.3).unwrap(),
    )
    .unwrap();
    assert!(matches!(
        make(nonprincipal, body([0.0; 3]), vec![0.0; system.n_u]),
        Err(PlanarStokesError::Invalid(_))
    ));
    let out_of_plane =
        RigidBodyState::new(body([0.0; 3]).pose(), Vec3::new(0.0, 0.0, 0.01), Vec3::ZERO).unwrap();
    assert!(matches!(
        make(properties(), out_of_plane, vec![0.0; system.n_u]),
        Err(PlanarStokesError::Invalid(_))
    ));
}
