//! Native adhesive rolling/torsion loss and original finite-cell heating.
//!
//! The original sealed mechanical history is advanced once, internally. Only
//! an explicitly declared caloric fraction of its irreversible loss enters the
//! existing massless-face heat network. Recoverable bond storage and applied
//! body work stay separate; the remaining loss retains its named noncaloric
//! account. Signed heat into either finite body follows actual conduction,
//! including hot-to-cold exchange, rather than an authored A/B heat split.
//!
//! This is a fixed-source, fixed-area, held-pose operator split. It supplies no
//! normal reaction, no-slip constraint, history rotation, area evolution or
//! temperature dependence. Mechanical coefficients do not change during the
//! thermal solve. Caloric material domains, finite heat capacity, conduction,
//! other sources and cancellation retain their existing owners.

