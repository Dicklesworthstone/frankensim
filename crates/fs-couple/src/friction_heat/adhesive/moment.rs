/// Explicit physical conversion of adhesive hysteresis, with no default.
/// This is a caloric/noncaloric split; the finite network solves the A/B heat.
#[derive(Clone, Debug, PartialEq)]
pub struct AdhesiveMomentHeatPartition {
    caloric_fraction: f64,
    noncaloric_destination: Option<String>,
}
impl AdhesiveMomentHeatPartition {
    /// The caller must justify this fraction for its selected rolling/torsion
    /// calibration. A nonzero remainder requires a named physical destination.
    pub fn new(
        caloric_fraction: f64,
        noncaloric_destination: Option<String>,
    ) -> Result<Self, AdhesiveMomentHeatError> {
        if !caloric_fraction.is_finite()
            || !(0.0..=1.0).contains(&caloric_fraction)
            || noncaloric_destination
                .as_ref()
                .is_some_and(|s| s.trim().is_empty())
            || (caloric_fraction < 1.0 && noncaloric_destination.is_none())
        {
            return Err(AdhesiveMomentHeatError::Invalid(
                "explicit caloric fraction in [0,1] and named noncaloric remainder required",
            ));
        }
        Ok(Self {
            caloric_fraction,
            noncaloric_destination,
        })
    }
    pub const fn caloric_fraction(&self) -> f64 {
        self.caloric_fraction
    }
    pub fn noncaloric_destination(&self) -> Option<&str> {
        self.noncaloric_destination.as_deref()
    }
    fn split<E>(&self, loss: f64) -> Result<AdhesiveMomentLoss, AdhesiveMomentHeatError<E>> {
        if !loss.is_finite() || loss < 0.0 {
            return Err(AdhesiveMomentHeatError::Invalid(
                "invalid native irreversible loss",
            ));
        }
        let generated_heat_j = loss * self.caloric_fraction;
        Ok(AdhesiveMomentLoss {
            irreversible_loss_j: loss,
            generated_heat_j,
            noncaloric_loss_j: loss - generated_heat_j,
        })
    }
}

/// Loss conversion during one increment or accumulated since this heat binding.
/// Body-to-body conduction is not dissipation generated by the mechanical law.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct AdhesiveMomentLoss {
    irreversible_loss_j: f64,
    generated_heat_j: f64,
    noncaloric_loss_j: f64,
}
impl AdhesiveMomentLoss {
    pub const fn irreversible_loss_j(&self) -> f64 {
        self.irreversible_loss_j
    }
    pub const fn generated_heat_j(&self) -> f64 {
        self.generated_heat_j
    }
    pub const fn noncaloric_loss_j(&self) -> f64 {
        self.noncaloric_loss_j
    }
    fn add<E>(self, next: Self) -> Result<Self, AdhesiveMomentHeatError<E>> {
        let sum = |a, b| (Dd::from_f64(a) + Dd::from_f64(b)).to_f64();
        let total = Self {
            irreversible_loss_j: sum(self.irreversible_loss_j, next.irreversible_loss_j),
            generated_heat_j: sum(self.generated_heat_j, next.generated_heat_j),
            noncaloric_loss_j: sum(self.noncaloric_loss_j, next.noncaloric_loss_j),
        };
        if [
            total.irreversible_loss_j,
            total.generated_heat_j,
            total.noncaloric_loss_j,
        ]
        .iter()
        .any(|v| !v.is_finite() || *v < 0.0)
        {
            return Err(AdhesiveMomentHeatError::Invalid(
                "cumulative moment loss overflow",
            ));
        }
        Ok(total)
    }
}

#[derive(Clone, Copy, Debug)]
pub struct AdhesiveMomentHeatControls {
    pub mechanical: AdhesiveMomentMechanicalControls,
    pub thermal: AdhesiveMomentThermalControls,
}

#[derive(Debug)]
pub enum AdhesiveMomentHeatError<E = Infallible> {
    Invalid(&'static str),
    Rolling(RigidAdhesiveRollingError),
    Torsion(RigidAdhesiveTorsionError),
    Heat(CohesiveHeatError<E>),
    EnergyBalance {
        residual_j: f64,
        absolute_stage_residual_j: f64,
    },
}
impl<E> From<RigidAdhesiveRollingError> for AdhesiveMomentHeatError<E> {
    fn from(e: RigidAdhesiveRollingError) -> Self {
        Self::Rolling(e)
    }
}
impl<E> From<RigidAdhesiveTorsionError> for AdhesiveMomentHeatError<E> {
    fn from(e: RigidAdhesiveTorsionError) -> Self {
        Self::Torsion(e)
    }
}
impl<E> From<CohesiveHeatError<E>> for AdhesiveMomentHeatError<E> {
    fn from(e: CohesiveHeatError<E>) -> Self {
        Self::Heat(e)
    }
}
impl<E> From<DepositionError> for AdhesiveMomentHeatError<E> {
    fn from(e: DepositionError) -> Self {
        Self::Heat(e.into())
    }
}
impl<E: core::fmt::Debug> core::fmt::Display for AdhesiveMomentHeatError<E> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "adhesive moment heat refused: {self:?}")
    }
}
impl<E: std::error::Error + 'static> std::error::Error for AdhesiveMomentHeatError<E> {}

/// Retained native memory, original source/receivers and noncaloric loss account.
/// An already loaded native state is admitted without resetting its spring.
#[derive(Clone)]
pub struct AdhesiveMomentHeat<'s> {
    native: NativeAdhesiveMoment<'s>,
    body_ids: [u64; 2],
    caloric: [&'s EquilibriumEnthalpyPhaseCurve; 2],
    route: FrictionHeatRoute,
    partition: AdhesiveMomentHeatPartition,
    time_s: f64,
    losses: AdhesiveMomentLoss,
}

pub struct AdhesiveMomentHeatReport<P> {
    pub mechanical: AdhesiveMomentMechanicalReport,
    pub heat: FrictionHeatNetworkReport,
    pub losses: AdhesiveMomentLoss,
    pub noncaloric_destination: Option<String>,
    pub source: P,
    pub nonlinear: NewtonReport,
    pub thermal_trials: usize,
    pub target_time_s: f64,
    /// Delta K + Delta U_bond + Delta H + noncaloric loss - body work - other heat.
    pub combined_energy_residual_j: f64,
    /// Independent mechanical, thermal and partition residual magnitudes.
    /// Opposite-sign stage errors cannot conceal each other.
    pub absolute_stage_residual_j: f64,
}

/// All fields remain private until this complete proposal has passed every gate.
pub struct AdhesiveMomentHeatCandidate<'s, 't, P> {
    bodies_after: [RigidBodyState; 2],
    history: AdhesiveMomentHeat<'s>,
    thermal: DepositionSimulation<'t>,
    report: AdhesiveMomentHeatReport<P>,
}
impl<'s, 't, P> AdhesiveMomentHeatCandidate<'s, 't, P> {
    pub const fn bodies_after(&self) -> &[RigidBodyState; 2] {
        &self.bodies_after
    }
    pub const fn history(&self) -> &AdhesiveMomentHeat<'s> {
        &self.history
    }
    pub const fn thermal(&self) -> &DepositionSimulation<'t> {
        &self.thermal
    }
    pub const fn report(&self) -> &AdhesiveMomentHeatReport<P> {
        &self.report
    }
    /// Original native A/B order, retained history, finite thermal state, audit.
    pub fn into_parts(
        self,
    ) -> (
        [RigidBodyState; 2],
        AdhesiveMomentHeat<'s>,
        DepositionSimulation<'t>,
        AdhesiveMomentHeatReport<P>,
    ) {
        (self.bodies_after, self.history, self.thermal, self.report)
    }
}

impl<'s> AdhesiveMomentHeat<'s> {
    /// Bind the original sealed history to its actual ordered caloric laws.
    /// `body_ids` explicitly maps the native A/B pair to original thermal bodies.
    /// The route must have the original attached JKR area. Spatial coincidence
    /// and original held native geometry are checked on every motion proposal.
    /// The loss ledger starts at binding; no prior loss is relabeled as heat.
    pub fn new(
        native: NativeAdhesiveMoment<'s>,
        body_ids: [u64; 2],
        caloric: [&'s EquilibriumEnthalpyPhaseCurve; 2],
        route: FrictionHeatRoute,
        thermal: &DepositionSimulation<'_>,
        partition: AdhesiveMomentHeatPartition,
    ) -> Result<Self, AdhesiveMomentHeatError> {
        native.stored_energy_j()?;
        let history = Self {
            native,
            body_ids,
            caloric,
            route,
            partition,
            time_s: thermal.time_s(),
            losses: AdhesiveMomentLoss::default(),
        };
        history.validate_receivers(thermal)?;
        Ok(history)
    }
    pub const fn native(&self) -> NativeAdhesiveMoment<'s> {
        self.native
    }
    pub const fn route(&self) -> &FrictionHeatRoute {
        &self.route
    }
    pub const fn partition(&self) -> &AdhesiveMomentHeatPartition {
        &self.partition
    }
    pub const fn time_s(&self) -> f64 {
        self.time_s
    }
    pub const fn losses(&self) -> AdhesiveMomentLoss {
        self.losses
    }

    /// Prepare original wrench-driven motion once, then solve finite calorics.
    /// `resolve` supplies endpoint bulk conductivities and OTHER thermal sources.
    /// Its payload is staged; it must not publish state or reinsert the loss.
    /// Numerical guesses do not prescribe face temperature or add heat capacity.
    /// Mechanical coefficients stay fixed even if temperature changes; this
    /// split must be refined for temperature-feedback or fast transient accuracy.
    #[allow(clippy::too_many_arguments)]
    pub fn propose<'t, P, E>(
        &self,
        bodies: &[RigidBodyState],
        properties: &[MassProperties],
        wrenches: [Wrench; 2],
        thermal: &DepositionSimulation<'t>,
        dt_s: f64,
        controls: AdhesiveMomentHeatControls,
        energy_guess_j: &[f64],
        temperature_guess_k: f64,
        resolve: impl Fn(
            &DepositionSimulation<'t>,
            &[u64],
            &[f64],
        ) -> Result<AdhesiveMomentHeatSource<P>, E>,
        gate: &CancelGate,
    ) -> Result<AdhesiveMomentHeatCandidate<'s, 't, P>, AdhesiveMomentHeatError<E>> {
        let check = || {
            if gate.is_requested() {
                Err(DepositionError::Cancelled)
            } else {
                Ok(())
            }
        };
        check()?;
        let target = self.time_s + dt_s;
        if self.time_s != thermal.time_s()
            || !dt_s.is_finite()
            || dt_s <= 0.0
            || !target.is_finite()
            || target <= self.time_s
        {
            return Err(AdhesiveMomentHeatError::Invalid(
                "synchronized positive physical interval required",
            ));
        }
        self.validate_receivers(thermal)?;
        let network = FrictionHeatNetworkStep::new(
            thermal,
            target,
            &[&self.route],
            controls.thermal.maximum_interfaces,
            check,
        )?;
        // The public native diagnostic reports are never accepted as inputs.
        let native = self.native.prepare(
            bodies,
            properties,
            wrenches,
            network.duration_s(),
            controls.mechanical,
            gate,
        )?;
        self.validate_geometry(bodies, properties, controls.mechanical.geometry_tolerance_m)?;
        let balance = native.report.balance();
        let losses = self.partition.split(balance.irreversible_loss_j)?;
        let cumulative = self.losses.add(losses)?;
        let solved = solve_frozen_cohesive_heat(
            thermal,
            &network,
            &[temperature_guess_k],
            &[losses.generated_heat_j],
            controls.thermal,
            energy_guess_j,
            resolve,
            gate,
        )?;
        self.validate_receivers(&solved.thermal)?;
        let heat = &solved.heat;
        let combined = (Dd::from_f64(balance.kinetic_change_j)
            + Dd::from_f64(balance.storage_change_j)
            + Dd::from_f64(heat.thermal.stored_energy_change_j)
            + Dd::from_f64(losses.noncaloric_loss_j)
            - Dd::from_f64(balance.external_work_j)
            - Dd::from_f64(heat.external_heat_j))
        .to_f64();
        let partition_residual = (Dd::from_f64(losses.generated_heat_j)
            + Dd::from_f64(losses.noncaloric_loss_j)
            - Dd::from_f64(losses.irreversible_loss_j))
        .to_f64();
        let absolute_stages = (Dd::from_f64(balance.residual_j.abs())
            + Dd::from_f64(heat.total_energy_residual_j.abs())
            + Dd::from_f64(partition_residual.abs()))
        .to_f64();
        if heat.dissipated_j != losses.generated_heat_j
            || [combined, absolute_stages]
                .iter()
                .any(|r| !r.is_finite() || r.abs() > controls.thermal.combined_energy_tolerance_j)
        {
            return Err(AdhesiveMomentHeatError::EnergyBalance {
                residual_j: combined,
                absolute_stage_residual_j: absolute_stages,
            });
        }
        let mut history = self.clone();
        history.native = native.after;
        history.time_s = target;
        history.losses = cumulative;
        check()?;
        Ok(AdhesiveMomentHeatCandidate {
            bodies_after: native.bodies_after,
            history,
            thermal: solved.thermal,
            report: AdhesiveMomentHeatReport {
                mechanical: native.report,
                heat: solved.heat,
                losses,
                noncaloric_destination: self.partition.noncaloric_destination.clone(),
                source: solved.source,
                nonlinear: solved.nonlinear,
                thermal_trials: solved.trials,
                target_time_s: target,
                combined_energy_residual_j: combined,
                absolute_stage_residual_j: absolute_stages,
            },
        })
    }

    /// Publish the native bodies, original memory, retained loss and calorics once.
    /// Every failure, including cancellation after thermal convergence, leaves
    /// all accepted owners unchanged. Unrelated native bodies are untouched.
    #[allow(clippy::too_many_arguments)]
    pub fn apply<'t, P, E>(
        &mut self,
        bodies: &mut [RigidBodyState],
        properties: &[MassProperties],
        wrenches: [Wrench; 2],
        thermal: &mut DepositionSimulation<'t>,
        dt_s: f64,
        controls: AdhesiveMomentHeatControls,
        energy_guess_j: &[f64],
        temperature_guess_k: f64,
        resolve: impl Fn(
            &DepositionSimulation<'t>,
            &[u64],
            &[f64],
        ) -> Result<AdhesiveMomentHeatSource<P>, E>,
        gate: &CancelGate,
    ) -> Result<AdhesiveMomentHeatReport<P>, AdhesiveMomentHeatError<E>> {
        let candidate = self.propose(
            bodies,
            properties,
            wrenches,
            thermal,
            dt_s,
            controls,
            energy_guess_j,
            temperature_guess_k,
            resolve,
            gate,
        )?;
        if gate.is_requested() {
            return Err(DepositionError::Cancelled.into());
        }
        let binding = self.native.binding();
        bodies[binding.body_a] = candidate.bodies_after[0];
        bodies[binding.body_b] = candidate.bodies_after[1];
        *self = candidate.history;
        *thermal = candidate.thermal;
        Ok(candidate.report)
    }
}
