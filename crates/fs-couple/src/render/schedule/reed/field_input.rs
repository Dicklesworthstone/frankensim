//! Authored primitive gas fields over the existing pack and field owners.
//!
//! This module parses data and associates explicit source IDs. It introduces no
//! thermodynamic, transport, interpolation, duct or pressure-observation law.

use super::{
    GasFieldResolution, GasRecord, Reader, ReedPerformanceError, Row, ThermochemicalSources, bad,
};
use fs_matdb::QueryPoint;
use fs_material::gas_field::{AxialGasField, MAX_FIELD_STATIONS};
use fs_material::gas_field::input::PrimitiveGasColumns as SourceColumns;
use fs_material::gas_species::input::GasInputError;

pub(super) mod steady;

/// gas_field continuous STEPS_PER_SPAN STATIONS mole SPECIES_COUNT ID...
/// gas_field midpoint CELLS_PER_SEGMENT STATIONS mole SPECIES_COUNT ID...
/// gas_field CELLS_PER_SEGMENT STATIONS mole SPECIES_COUNT ID... (midpoint)
/// gas_station X_M T_K FRACTION... (one row per station, in declared ID order)
///
/// Ambient supplies the one common pressure. Species are sorted together with
/// their columns before entering the original canonical-composition owner.
pub(super) fn read(
    reader: &mut Reader<'_>,
    sources: Option<&ThermochemicalSources<'_>>,
    pressure_pa: f64,
    records: &mut Vec<GasRecord>,
) -> Result<(AxialGasField, GasFieldResolution), ReedPerformanceError> {
    let mut row = reader.row("gas_field")?;
    let line = row.line;
    let resolution = read_resolution(&mut row)?;
    let stations = row.count(MAX_FIELD_STATIONS)?;
    if stations < 2 {
        return Err(bad(line, "gas_field needs at least two stations"));
    }
    let columns = SourceColumns::read(&mut row.words, sources, stations)
        .map_err(|error| column_error(row.line, error))?;
    row.finish()?;
    let mut positions = Vec::with_capacity(stations);
    let mut states = Vec::with_capacity(stations);
    let mut station_lines = Vec::with_capacity(stations);
    for _ in 0..stations {
        let mut row = reader.row("gas_station")?;
        station_lines.push(row.line);
        positions.push(row.scalar()?);
        states.push(columns.read_state(&mut row.words)
            .map_err(|error| column_error(row.line, error))?);
        row.finish()?;
    }
    let (model, phase) = columns.into_parts();
    let field = AxialGasField::new(
        positions,
        pressure_pa,
        states,
        model,
        QueryPoint::new(),
        phase,
    )
    .map_err(|source| ReedPerformanceError::Gas { line, source })?;

    // The same gas-record surface retains exact field-knot receipts for both
    // prescribed fields and fields generated by the original thermal owner.
    for (&position, &line) in field.stations_m().iter().zip(&station_lines) {
        let state = field
            .state_at(position)
            .map_err(|source| ReedPerformanceError::Gas { line, source })?;
        records.push(GasRecord::Thermochemical(state));
    }
    Ok((field, resolution))
}

fn read_resolution(row: &mut Row<'_>) -> Result<GasFieldResolution, ReedPerformanceError> {
    let resolution = match row.words.clone().next() {
        Some("continuous") => {
            row.word()?;
            GasFieldResolution::Continuous(fs_duct::RiccatiSteps(
                row.count(fs_duct::profile::MAX_RICCATI_STEPS)?,
            ))
        }
        mode => {
            if mode == Some("midpoint") {
                row.word()?;
            }
            GasFieldResolution::Midpoint(
                row.count(crate::driving_point::regional::MAX_REGIONAL_SEGMENTS)?,
            )
        }
    };
    if matches!(
        resolution,
        GasFieldResolution::Midpoint(0) | GasFieldResolution::Continuous(fs_duct::RiccatiSteps(0))
    ) {
        return Err(bad(row.line, "gas field needs positive spatial resolution"));
    }
    Ok(resolution)
}

// Keep source lines in the performance grammar; material admission is shared.
fn column_error(line: usize, error: GasInputError) -> ReedPerformanceError {
    match error {
        GasInputError::Input(what) => bad(line, what),
        GasInputError::Material(source) => ReedPerformanceError::Gas { line, source },
    }
}

