//! Continuous physical tone performances through the existing pressure/PCM path.
//!
//! Gain envelopes act on the original physical input ports, before the nonlinear solve.
//! Carrier phases and all mechanical/material histories continue through silence
//! and re-attack. Callback boundaries have no physical significance.
//!
//! This observer emits compact baffled-monopole **interval-mean source-time**
//! pressure. Distance sets geometric spreading; no propagation delay, receiver
//! directivity or acoustic reaction is inferred. It is not the retarded waveform
//! produced by the separate linear [`super::CompactPlateVoice`] observer.
//! The prepared source's carrier guard does not bound harmonics generated by
//! nonlinear storage or gain knots. A refined source clock can feed the existing
//! [`crate::pcm_wav::observation::DecimatedRenderer`] before calibrated PCM export.

use crate::pcm_wav::observation::PressureRenderer;
use crate::render::RenderError;
use crate::thin_plate::{PreparedVkStep, PreparedVkTones};

/// Clock, finite performance window and cold driver resource admission.
#[derive(Debug, Clone, Copy)]
pub struct VkToneRenderConfig {
    /// Must exactly match the prepared source's `1.0 / sample_rate_hz` interval.
    pub sample_rate_hz: u32,
    /// Number of physical intervals admitted from this performance's start.
    pub samples: u64,
    /// Largest pressure callback; no callback-sized private buffer is needed.
    pub max_block_len: usize,
    /// Maximum driver payload: effort/phase arrays and envelope cursor metadata.
    /// The already prepared source, caller-owned knots and allocator metadata
    /// have separate ownership and are excluded.
    pub max_driver_bytes: usize,
    /// Maximum total borrowed gain knots inspected during construction.
    pub max_envelope_knots: usize,
    /// Positive finite acoustic density used only by the compact observer.
    pub density_kg_m3: f64,
    /// Positive finite spreading distance [m], with no inferred time of flight.
    pub distance_m: f64,
}

/// One signed dimensionless effort gain at an exact source-sample boundary.
#[derive(Debug, Clone, Copy)]
pub struct VkToneGainKnot {
    pub sample: u64,
    pub gain: f64,
}

/// Piecewise-affine effort gain for one original port/carrier coefficient pair.
/// Knots start at sample zero and strictly increase within the performance
/// window. The final gain is held. Undeclared pairs keep unit gain.
#[derive(Debug, Clone, Copy)]
pub struct VkToneEnvelope<'a> {
    pub port: usize,
    pub tone: usize,
    pub knots: &'a [VkToneGainKnot],
}

struct GainCurve<'a> {
    knots: &'a [VkToneGainKnot],
    interval: usize,
}

/// Bounded mono consumer of the original nonlinear tone owner.
///
/// Caller-authored initial cosine/sine coefficients retain each original port's
/// effort units: N on a force port or Pa on a face-pressure port. They are indexed
/// `port * tone_count + tone`, in the prepared source's frequency order.
/// A warm callback allocates no driver memory. Accepted intervals publish their
/// mechanics, source phase, gain cursor and sample clock together. A failed
/// callback may contain an accepted prefix and permanently poisons this driver,
/// following [`PressureRenderer`]'s existing streaming contract.
pub struct VkTonePressureRenderer<'a> {
    source: PreparedVkTones,
    config: VkToneRenderConfig,
    cosine: Vec<f64>,
    sine: Vec<f64>,
    next_cosine: Vec<f64>,
    next_sine: Vec<f64>,
    force_cosine: Vec<f64>,
    force_sine: Vec<f64>,
    force_cosine_end: Vec<f64>,
    force_sine_end: Vec<f64>,
    curves: Vec<Option<GainCurve<'a>>>,
    completed: u64,
    last_step: Option<PreparedVkStep>,
    poisoned: bool,
}

impl<'a> VkTonePressureRenderer<'a> {
    /// Start fixed-amplitude tones at the supplied phases, preserving all
    /// existing source state. Requires a fixed-amplitude prepared source.
    pub fn fixed(
        source: PreparedVkTones,
        cosine_n: &[f64],
        sine_n: &[f64],
        config: VkToneRenderConfig,
    ) -> Result<Self, RenderError> {
        Self::new(source, cosine_n, sine_n, &[], config, false)
    }

    /// Start piecewise-affine physical effort envelopes on an affine prepared
    /// source. Knot storage remains borrowed and immutable for the performance.
    /// Both effort endpoints use the SAME interval-start carrier basis; gain
    /// changes never rotate a carrier early or reset it at zero gain.
    pub fn affine(
        source: PreparedVkTones,
        cosine_n: &[f64],
        sine_n: &[f64],
        envelopes: &[VkToneEnvelope<'a>],
        config: VkToneRenderConfig,
    ) -> Result<Self, RenderError> {
        Self::new(source, cosine_n, sine_n, envelopes, config, true)
    }

    fn new(
        source: PreparedVkTones,
        cosine_n: &[f64],
        sine_n: &[f64],
        envelopes: &[VkToneEnvelope<'a>],
        config: VkToneRenderConfig,
        affine: bool,
    ) -> Result<Self, RenderError> {
        if config.sample_rate_hz == 0
            || source.time_step_s() != f64::from(config.sample_rate_hz).recip()
            || config.samples == 0
            || config.max_block_len == 0
            || !config.density_kg_m3.is_finite()
            || config.density_kg_m3 <= 0.0
            || !config.distance_m.is_finite()
            || config.distance_m <= 0.0
            || source.is_affine() != affine
        {
            return Err(invalid(
                "plate tone source, envelope kind, clock or observer configuration disagree",
            ));
        }
        let count = source
            .port_count()
            .checked_mul(source.tone_count())
            .ok_or_else(|| sizing("plate tone coefficient extent overflows"))?;
        if cosine_n.len() != count
            || sine_n.len() != count
            || envelopes.len() > count
            || cosine_n.iter().chain(sine_n).any(|x| !x.is_finite())
        {
            return Err(invalid(
                "plate tone forces require complete finite original port/tone quadratures",
            ));
        }
        let bytes_per_pair = if affine {
            8 * core::mem::size_of::<f64>() + core::mem::size_of::<Option<GainCurve<'a>>>()
        } else {
            4 * core::mem::size_of::<f64>()
        };
        if count
            .checked_mul(bytes_per_pair)
            .is_none_or(|bytes| bytes > config.max_driver_bytes)
        {
            return Err(sizing("plate tone driver exceeds its payload budget"));
        }
        let knots = envelopes
            .iter()
            .try_fold(0usize, |n, curve| n.checked_add(curve.knots.len()))
            .ok_or_else(|| sizing("plate tone envelope knot count overflows"))?;
        if knots > config.max_envelope_knots {
            return Err(sizing("plate tone envelopes exceed their knot budget"));
        }
        let mut curves = Vec::new();
        if affine {
            curves
                .try_reserve_exact(count)
                .map_err(|_| sizing("plate tone envelope allocation refused"))?;
            curves.resize_with(count, || None);
        }
        for envelope in envelopes {
            if envelope.port >= source.port_count()
                || envelope.tone >= source.tone_count()
                || envelope.knots.is_empty()
                || envelope.knots[0].sample != 0
                || envelope
                    .knots
                    .iter()
                    .any(|k| k.sample > config.samples || !k.gain.is_finite())
                || envelope
                    .knots
                    .windows(2)
                    .any(|w| w[0].sample >= w[1].sample)
            {
                return Err(invalid(
                    "plate tone gain knots need a valid original pair and ordered finite gains within the window",
                ));
            }
            let index = envelope.port * source.tone_count() + envelope.tone;
            if curves[index].is_some() {
                return Err(invalid(
                    "plate tone gain envelope repeats an original port/tone pair",
                ));
            }
            curves[index] = Some(GainCurve {
                knots: envelope.knots,
                interval: 0,
            });
        }
        for index in 0..count {
            let gain = curves
                .get(index)
                .and_then(Option::as_ref)
                .map_or(1.0, |curve| {
                    curve.knots.iter().map(|k| k.gain.abs()).fold(0.0, f64::max)
                });
            if !(cosine_n[index].hypot(sine_n[index]) * gain).is_finite() {
                return Err(invalid(
                    "plate tone carrier or enveloped force amplitude is not representable",
                ));
            }
        }
        let endpoints = if affine { count } else { 0 };
        let mut cosine = zeroes(count)?;
        let mut sine = zeroes(count)?;
        cosine.copy_from_slice(cosine_n);
        sine.copy_from_slice(sine_n);
        Ok(Self {
            source,
            config,
            cosine,
            sine,
            next_cosine: zeroes(count)?,
            next_sine: zeroes(count)?,
            force_cosine: zeroes(endpoints)?,
            force_sine: zeroes(endpoints)?,
            force_cosine_end: zeroes(endpoints)?,
            force_sine_end: zeroes(endpoints)?,
            curves,
            completed: 0,
            last_step: None,
            poisoned: false,
        })
    }

    /// Immutable original mechanical/material state and stored energy.
    #[must_use]
    pub fn source(&self) -> &PreparedVkTones {
        &self.source
    }

    /// Last accepted pressure, volume flow and original work/heat record.
    #[must_use]
    pub fn last_step(&self) -> Option<&PreparedVkStep> {
        self.last_step.as_ref()
    }

    /// Last accepted original resistance observations, in source channel order.
    /// They retain the source's physical meaning and need not partition heat.
    #[must_use]
    pub fn channel_heat_j(&self) -> &[f64] {
        self.source.channel_heat_j()
    }

    fn step(&mut self) -> Result<f64, RenderError> {
        for index in 0..self.cosine.len() {
            let (c, s) = self
                .source
                .advance_force_phase(
                    index % self.source.tone_count(),
                    self.cosine[index],
                    self.sine[index],
                )
                .map_err(RenderError::Voice)?;
            self.next_cosine[index] = c;
            self.next_sine[index] = s;
            if self.source.is_affine() {
                let [start, end] = self.curves[index]
                    .as_ref()
                    .map_or([1.0, 1.0], |curve| curve.endpoints(self.completed));
                let values = [
                    start * self.cosine[index],
                    start * self.sine[index],
                    end * self.cosine[index],
                    end * self.sine[index],
                ];
                if values.iter().any(|x| !x.is_finite()) {
                    return Err(invalid("plate tone force envelope overflow"));
                }
                [
                    self.force_cosine[index],
                    self.force_sine[index],
                    self.force_cosine_end[index],
                    self.force_sine_end[index],
                ] = values;
            }
        }
        let frame = if self.source.is_affine() {
            self.source.drive_affine_and_radiate(
                &self.force_cosine,
                &self.force_sine,
                &self.force_cosine_end,
                &self.force_sine_end,
                self.config.density_kg_m3,
                self.config.distance_m,
            )
        } else {
            self.source.drive_and_radiate(
                &self.cosine,
                &self.sine,
                self.config.density_kg_m3,
                self.config.distance_m,
            )
        }
        .map_err(RenderError::Voice)?;
        core::mem::swap(&mut self.cosine, &mut self.next_cosine);
        core::mem::swap(&mut self.sine, &mut self.next_sine);
        self.completed += 1;
        for curve in self.curves.iter_mut().flatten() {
            if curve
                .knots
                .get(curve.interval + 1)
                .is_some_and(|k| k.sample == self.completed)
            {
                curve.interval += 1;
            }
        }
        self.last_step = Some(frame);
        Ok(frame.pressure_pa)
    }
}

impl GainCurve<'_> {
    fn endpoints(&self, sample: u64) -> [f64; 2] {
        let left = self.knots[self.interval];
        let Some(right) = self.knots.get(self.interval + 1) else {
            return [left.gain; 2];
        };
        let value = |at| {
            if at == left.sample {
                return left.gain;
            }
            if at == right.sample {
                return right.gain;
            }
            let t = (at - left.sample) as f64 / (right.sample - left.sample) as f64;
            left.gain * (1.0 - t) + right.gain * t
        };
        [value(sample), value(sample + 1)]
    }
}

impl PressureRenderer for VkTonePressureRenderer<'_> {
    fn samples_rendered(&self) -> u64 {
        self.completed
    }
    fn max_block_len(&self) -> usize {
        self.config.max_block_len
    }
    fn validate_sample_rate(&self, rate: u32) -> Result<(), RenderError> {
        if self.poisoned {
            return Err(RenderError::Poisoned);
        }
        if rate != self.config.sample_rate_hz {
            return Err(invalid(
                "plate tone output rate differs from its prepared source clock",
            ));
        }
        Ok(())
    }
    fn validate_sample_count(&self, samples: u64) -> Result<(), RenderError> {
        if self.poisoned {
            return Err(RenderError::Poisoned);
        }
        if samples > self.config.samples - self.completed {
            return Err(sizing(
                "plate tone request exceeds its admitted performance window",
            ));
        }
        Ok(())
    }
    fn block(&mut self, output: &mut [f64]) -> Result<(), RenderError> {
        self.validate_sample_count(output.len() as u64)?;
        if output.is_empty() {
            return Err(RenderError::EmptyBlock);
        }
        if output.len() > self.config.max_block_len {
            return Err(sizing(
                "plate tone callback exceeds its admitted block length",
            ));
        }
        for slot in output {
            match self.step() {
                Ok(pressure) => *slot = pressure,
                Err(error) => {
                    self.poisoned = true;
                    return Err(error);
                }
            }
        }
        Ok(())
    }
}

fn zeroes(count: usize) -> Result<Vec<f64>, RenderError> {
    let mut values = Vec::new();
    values
        .try_reserve_exact(count)
        .map_err(|_| sizing("plate tone force buffer allocation refused"))?;
    values.resize(count, 0.0);
    Ok(values)
}
fn invalid(what: &'static str) -> RenderError {
    RenderError::Control { what }
}
fn sizing(what: &'static str) -> RenderError {
    RenderError::Sizing { what }
}
