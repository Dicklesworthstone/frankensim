//! Infer the wound Model D bass courses (MIDI 21-40) by algebraic inversion of
//! the embedded scale's line density and bending stiffness, and print one
//! complete 88-key string construction (native).
//!
//! RT-0425 homogenizes each wound string: its EI = E_RT pi d^4/64 with
//! E_RT = 2.02e11 Pa (INRIA RT-0425 section 3.2) defines an effective diameter,
//! and its density carries the wrap. With the sourced steel modulus and
//! density of the core pack and the sourced density of the wrap pack:
//! - the core carries EI: d_core = (64 EI / (pi E_steel))^(1/4);
//! - the wrap carries the rest of the line mass: mu - rho_steel pi d_core^2/4;
//! - the wrap is one close-wound wire of that mass, found by bisection on the
//!   production HelicalWrapping owner.
//! Every key must satisfy d_core < d_eff and a positive wrap mass, or the run
//! refuses. Nothing is fitted: these are measured quantities inverted exactly.
//! Plain courses (MIDI 41-108) are copied from the given plain construction.
//!
//! usage: infer_wound_construction <steel core pack> <wrap pack> <plain construction.csv>
use fs_live_piano::{kernel::SCALE_CSV, preparation::materials::operating_point, refmods::geometry};
use fs_matdb::NormalizedMaterialCardPack;
use fs_material::section::wound::{HelicalWrap, HelicalWrapping, close_wound_pitch_m};
use fs_material::section::{ConcentricElasticSection, ConcentricMaterialLayer};
use fs_material::state_point::{DENSITY_PROPERTY, MaterialPropertySelection, ResolvedMaterialStatePoint,
    ScalarAdmissibility, ScalarPropertyRequirement, YOUNG_MODULUS_PROPERTY, resolve_material_state_point};
use fs_qty::{Density, Pressure};
use std::f64::consts::PI;

/// RT-0425 section 3.2: the homogenized relation behind the scale's EI.
const E_RT0425: f64 = 2.02e11;

fn state(path: &str, with_modulus: bool) -> ResolvedMaterialStatePoint {
    let pack = NormalizedMaterialCardPack::from_bytes(&std::fs::read(path).expect("pack file")).expect("pack");
    let mut requirements = vec![ScalarPropertyRequirement::try_new(DENSITY_PROPERTY, Density::DIMS,
        ScalarAdmissibility::StrictlyPositive).unwrap()];
    if with_modulus {
        requirements.push(ScalarPropertyRequirement::try_new(YOUNG_MODULUS_PROPERTY, Pressure::DIMS,
            ScalarAdmissibility::StrictlyPositive).unwrap());
    }
    let point = operating_point("T", 293.15, "frequency", 1000.0).expect("operating point");
    resolve_material_state_point(pack.card(), &point, &requirements, MaterialPropertySelection::SingleClaimOnly)
        .expect("resolved state")
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    assert!(args.len() == 3, "usage: infer_wound_construction <steel core pack> <wrap pack> <plain construction.csv>");
    let steel = state(&args[0], true);
    let wrap = state(&args[1], false);
    let plain = std::fs::read_to_string(&args[2]).expect("plain construction");
    let value = |s: &ResolvedMaterialStatePoint, name: &str| s.property(name).expect("property").value_si();
    let (rho_steel, e_steel) = (value(&steel, DENSITY_PROPERTY), value(&steel, YOUNG_MODULUS_PROPERTY));
    let scale = geometry::read_scale(SCALE_CSV).expect("embedded scale");
    println!("# Complete 88-key Model D construction. MIDI 21-40: wound courses inferred by exact inversion of the");
    println!("# embedded scale's mu and EI (RT-0425, E_RT = 2.02e11 Pa) with the core pack's E = {e_steel} Pa and density");
    println!("# {rho_steel} kg/m^3 and the wrap pack's density {} kg/m^3: core from EI, one close-wound wrap from the", value(&wrap, DENSITY_PROPERTY));
    println!("# remaining line mass. MIDI 41-108: the plain RT-0425 cores. Pack 0 = core steel, pack 1 = wrap metal.");
    println!("# Generated by examples/infer_wound_construction.rs; per-key inversion values follow each wound key.");
    println!("frankensim-piano-materials-v2\ntension,target-pitch\nstrength,breaking_stress_1100um_untreated");
    println!("loss,thermoelastic\nkey,layer,outer_radius_m,wire_diameter_m,pitch_m,material_index");
    for course in scale.iter().filter(|c| c.midi <= 40) {
        let ei = course.flexural_rigidity_nm2;
        let d_eff = (64.0 * ei / (PI * E_RT0425)).powf(0.25);
        let d_core = (64.0 * ei / (PI * e_steel)).powf(0.25);
        let wrap_mass = course.linear_density_kg_m - rho_steel * PI * d_core * d_core / 4.0;
        assert!(d_core < d_eff && wrap_mass > 0.0,
            "key {}: inversion inconsistent (d_core {d_core}, d_eff {d_eff}, wrap mass {wrap_mass})", course.midi);
        let core = ConcentricElasticSection::try_new(0.0, vec![ConcentricMaterialLayer {
            outer_radius_m: 0.5 * d_core, material: steel.clone() }]).expect("core section");
        let mass_of = |d: f64| HelicalWrapping::try_new(&core, vec![HelicalWrap { wire_diameter_m: d,
            pitch_m: close_wound_pitch_m(d_core, d).expect("pitch"), material: wrap.clone() }])
            .expect("wrapping").line_density_kg_m();
        let (mut lo, mut hi) = (1e-7, 20.0 * d_core);
        assert!(mass_of(hi) > wrap_mass, "key {}: wrap mass beyond the search range", course.midi);
        for _ in 0..200 {
            let mid = 0.5 * (lo + hi);
            if mass_of(mid) < wrap_mass { lo = mid; } else { hi = mid; }
        }
        let d_wrap = 0.5 * (lo + hi);
        println!("# key {}: d_eff {:.5} mm, core {:.5} mm, wrap {:.5} mm, outer {:.4} mm, wrap mass {:.6} of {:.6} kg/m",
            course.midi, d_eff * 1e3, d_core * 1e3, d_wrap * 1e3, (d_core + 2.0 * d_wrap) * 1e3, mass_of(d_wrap),
            course.linear_density_kg_m);
        println!("{},core,{:e},,,0\n{},wrap,,{:e},close,1", course.midi, 0.5 * d_core, course.midi, d_wrap);
    }
    for line in plain.lines().filter(|line| line.contains(",core,")) {
        println!("{line}");
    }
}
